package auth

import (
	"errors"
	"fmt"
	"time"

	"golang.org/x/crypto/bcrypt"
)

// RecoveryMethod is how identity is verified during account recovery.
type RecoveryMethod string

const (
	// RecoveryOTPSMS sends a one-time password to the registered phone.
	// This is the primary path — everyone with a NIN has a phone.
	RecoveryOTPSMS RecoveryMethod = "OTP_SMS"
	// RecoveryBVNMatch confirms the taxpayer owns a bank account linked
	// to the BVN on file. Secondary path when the phone number has changed.
	RecoveryBVNMatch RecoveryMethod = "BVN_MATCH"
)

// RecoveryState is the lifecycle of one recovery attempt.
type RecoveryState string

const (
	RecoveryOTPSent   RecoveryState = "OTP_SENT"   // OTP delivered; waiting for submission
	RecoveryVerified  RecoveryState = "VERIFIED"    // identity confirmed; credential reset may proceed
	RecoveryCompleted RecoveryState = "COMPLETED"   // new credential accepted
	RecoveryExpired   RecoveryState = "EXPIRED"     // timed out or too many failed attempts
)

// RecoverySession is one account recovery attempt.
type RecoverySession struct {
	ID           string
	AccountID    string
	Method       RecoveryMethod
	State        RecoveryState
	// OTPHash is the bcrypt hash of the one-time password. The raw OTP is
	// generated by the caller, sent to the phone, and hashed before being
	// stored here. It is never stored in plaintext.
	OTPHash      []byte
	// AttemptCount is the number of incorrect OTP submissions. The session
	// is locked after maxOTPAttempts failures.
	AttemptCount int
	ExpiresAt    time.Time
	CompletedAt  *time.Time
}

const (
	otpExpiryMinutes  = 10
	bvnExpiryMinutes  = 30
	maxOTPAttempts    = 5
)

// Typed errors so callers can distinguish failure modes with errors.Is.
var (
	ErrAccountNotActive    = errors.New("auth: account is not active")
	ErrOTPExpired          = errors.New("auth: OTP session has expired")
	ErrOTPInvalid          = errors.New("auth: OTP is incorrect")
	ErrTooManyAttempts     = errors.New("auth: too many incorrect attempts — session locked")
	ErrSessionNotVerified  = errors.New("auth: session has not been verified")
	ErrSessionExpired      = errors.New("auth: session has expired")
)

// InitiateRecovery starts a recovery session. The OTP is generated and hashed
// by the caller (so this function never touches randomness or I/O), then sent
// to the phone. The session is created in OTP_SENT state.
//
// Returns ErrAccountNotActive if the account is suspended or pending.
func InitiateRecovery(account TaxpayerAccount, method RecoveryMethod, otpHash []byte, now time.Time) (RecoverySession, error) {
	if account.Status == AccountSuspended {
		return RecoverySession{}, fmt.Errorf("%w: status is %s", ErrAccountNotActive, account.Status)
	}
	expiry := otpExpiryMinutes
	if method == RecoveryBVNMatch {
		expiry = bvnExpiryMinutes
	}
	return RecoverySession{
		AccountID: account.ID,
		Method:    method,
		State:     RecoveryOTPSent,
		OTPHash:   otpHash,
		ExpiresAt: now.Add(time.Duration(expiry) * time.Minute),
	}, nil
}

// SubmitOTP verifies the provided OTP against the hashed value in the session
// and advances the session to VERIFIED on success.
//
// The comparison uses bcrypt.CompareHashAndPassword — constant-time comparison
// that prevents timing attacks. Never use == or bytes.Equal on OTP values.
func SubmitOTP(session RecoverySession, providedOTP string, now time.Time) (RecoverySession, error) {
	if session.State == RecoveryExpired {
		return session, ErrOTPExpired
	}
	if now.After(session.ExpiresAt) {
		session.State = RecoveryExpired
		return session, ErrOTPExpired
	}
	if err := bcrypt.CompareHashAndPassword(session.OTPHash, []byte(providedOTP)); err != nil {
		session.AttemptCount++
		if session.AttemptCount >= maxOTPAttempts {
			session.State = RecoveryExpired
			return session, ErrTooManyAttempts
		}
		return session, ErrOTPInvalid
	}
	session.State = RecoveryVerified
	return session, nil
}

// CompleteRecovery finalises the session after the identity has been confirmed.
// The caller is responsible for persisting newCredentialHash to the account.
//
// Returns ErrSessionNotVerified if the session has not passed SubmitOTP.
// Returns ErrSessionExpired if the session window has closed.
func CompleteRecovery(session RecoverySession, _ []byte, now time.Time) (RecoverySession, error) {
	if session.State != RecoveryVerified {
		return session, fmt.Errorf("%w: state is %s", ErrSessionNotVerified, session.State)
	}
	if now.After(session.ExpiresAt) {
		session.State = RecoveryExpired
		return session, ErrSessionExpired
	}
	t := now
	session.CompletedAt = &t
	session.State = RecoveryCompleted
	return session, nil
}
